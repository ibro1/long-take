const fs = require("node:fs");
const path = require("node:path");

const { AndroidConfig, withAndroidManifest, withDangerousMod } = require("expo/config-plugins");

/**
 * Keeps the stream keys off Google Drive and off the next phone.
 *
 * Destinations live in MMKV, which writes to `files/mmkv/` inside the app's
 * data directory, and a destination is an endpoint plus a stream key - the one
 * credential this phone carries. Android backs that directory up by default:
 * to the operator's Google Drive on a schedule, and to whatever handset they
 * set up next in a device-to-device transfer. Neither is a place a broadcast
 * credential should turn up, and neither is something the operator was asked
 * about.
 *
 * Both halves are excluded rather than backup being switched off wholesale.
 * The rest of the app's data - recordings metadata, settings, preferences - is
 * worth restoring onto a new phone, and turning `allowBackup` off would take
 * that with it. It also would not be enough: from Android 12 a device-to-device
 * transfer happens regardless of `allowBackup`, and only `<device-transfer>` in
 * the extraction rules stops it.
 *
 * Two files because Android changed the format: `fullBackupContent` is what
 * API 30 and below read, `dataExtractionRules` is what 31 and above read, and
 * a build that only declares one of them leaves the other half of the fleet
 * backing the keys up.
 *
 * Expressed as a plugin rather than by editing `android/`, because `android/`
 * is generated: the release build runs `expo prebuild`, which overwrites it.
 */

const FULL_BACKUP_RESOURCE = "framevane_backup_rules";
const DATA_EXTRACTION_RESOURCE = "framevane_data_extraction_rules";

/** MMKV's own root, relative to `getFilesDir()` - which is the `file` domain. */
const MMKV_PATH = "mmkv";

const GENERATED = "Generated by plugins/with-backup-rules.js. Edits here go on the next prebuild.";

const FULL_BACKUP_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- ${GENERATED} -->
<full-backup-content>
  <exclude domain="file" path="${MMKV_PATH}" />
</full-backup-content>
`;

const DATA_EXTRACTION_XML = `<?xml version="1.0" encoding="utf-8"?>
<!-- ${GENERATED} -->
<data-extraction-rules>
  <cloud-backup>
    <exclude domain="file" path="${MMKV_PATH}" />
  </cloud-backup>
  <device-transfer>
    <exclude domain="file" path="${MMKV_PATH}" />
  </device-transfer>
</data-extraction-rules>
`;

function withBackupRuleFiles(config) {
  return withDangerousMod(config, [
    "android",
    (config) => {
      const xmlDir = path.join(config.modRequest.platformProjectRoot, "app/src/main/res/xml");
      fs.mkdirSync(xmlDir, { recursive: true });
      fs.writeFileSync(path.join(xmlDir, `${FULL_BACKUP_RESOURCE}.xml`), FULL_BACKUP_XML);
      fs.writeFileSync(path.join(xmlDir, `${DATA_EXTRACTION_RESOURCE}.xml`), DATA_EXTRACTION_XML);
      return config;
    },
  ]);
}

function withBackupRuleAttributes(config) {
  return withAndroidManifest(config, (config) => {
    const application = AndroidConfig.Manifest.getMainApplicationOrThrow(config.modResults);
    application.$["android:fullBackupContent"] = `@xml/${FULL_BACKUP_RESOURCE}`;
    application.$["android:dataExtractionRules"] = `@xml/${DATA_EXTRACTION_RESOURCE}`;
    return config;
  });
}

module.exports = (config) => withBackupRuleAttributes(withBackupRuleFiles(config));
